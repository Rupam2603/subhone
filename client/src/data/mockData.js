export function filterProducts(list, params = {}) {
  let result = [...list];
  if (params.category) {
    result = result.filter((p) => (p.category || "").toLowerCase() === params.category.toLowerCase());
  }
  if (params.brand) {
    result = result.filter((p) => (p.brand || "").toLowerCase() === params.brand.toLowerCase());
  }
  if (params.dosageForm) {
    result = result.filter((p) => (p.dosageForm || "").toLowerCase() === params.dosageForm.toLowerCase());
  }
  if (params.veg !== undefined && params.veg !== "") {
    const isVeg = String(params.veg) === "true";
    result = result.filter((p) => p.veg === isVeg);
  }
  if (params.prescriptionRequired !== undefined && params.prescriptionRequired !== "") {
    const rx = String(params.prescriptionRequired) === "true";
    result = result.filter((p) => p.prescriptionRequired === rx);
  }
  if (params.q) {
    const q = params.q.toLowerCase();
    result = result.filter(
      (p) =>
        p.name?.toLowerCase().includes(q) ||
        p.brand?.toLowerCase().includes(q) ||
        p.category?.toLowerCase().includes(q) ||
        (p.tags && p.tags.some((t) => t.toLowerCase().includes(q)))
    );
  }

  // Sorting
  if (params.sort === "price-asc") {
    result.sort((a, b) => a.price - b.price);
  } else if (params.sort === "price-desc") {
    result.sort((a, b) => b.price - a.price);
  } else if (params.sort === "rating") {
    result.sort((a, b) => (b.rating || 0) - (a.rating || 0));
  } else if (params.sort === "discount") {
    result.sort((a, b) => {
      const discA = a.originalPrice ? (a.originalPrice - a.price) / a.originalPrice : 0;
      const discB = b.originalPrice ? (b.originalPrice - b.price) / b.originalPrice : 0;
      return discB - discA;
    });
  } else {
    // Default popularity
    result.sort((a, b) => (b.reviews || 0) - (a.reviews || 0));
  }

  return result;
}
